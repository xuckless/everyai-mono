#!/usr/bin/env bash
# Pins the Chrome for Testing build the Preview downloads when no browser is installed: the current Stable version
# (or $1), and our own SHA-256 of each platform's zip (Google publishes none), written to
# lib/features/code/live/chrome_pin.dart. Run it when a release should move to a newer Chrome; it downloads ~1 GB.
set -euo pipefail
cd "$(dirname "$0")/.."
json=$(curl -fsSL https://googlechromelabs.github.io/chrome-for-testing/known-good-versions-with-downloads.json)
version=${1:-$(curl -fsSL https://googlechromelabs.github.io/chrome-for-testing/last-known-good-versions.json | python3 -c 'import json,sys; print(json.load(sys.stdin)["channels"]["Stable"]["version"])')}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
out=lib/features/code/live/chrome_pin.dart
{
  echo "// Generated by tool/pin_chrome_for_testing.sh: the Chrome for Testing build the Preview downloads."
  echo ""
  echo "const chromeForTestingVersion = '$version';"
  echo ""
  echo "/// Platform → (zip URL, SHA-256 of the zip)."
  echo "const chromeForTestingPins = <String, (String, String)>{"
} > "$tmp/pin.dart"
for platform in mac-arm64 mac-x64 linux64 linux-arm64 win64; do
  url=$(VERSION="$version" PLATFORM="$platform" python3 -c '
import json, os, sys
for v in json.load(sys.stdin)["versions"]:
    if v["version"] == os.environ["VERSION"]:
        for d in v["downloads"].get("chrome", []):
            if d["platform"] == os.environ["PLATFORM"]:
                print(d["url"])
' <<<"$json")
  [ -n "$url" ] || { echo "no $platform build of $version" >&2; continue; }
  curl -fsSL -o "$tmp/$platform.zip" "$url"
  sum=$(shasum -a 256 "$tmp/$platform.zip" | cut -d' ' -f1)
  rm "$tmp/$platform.zip"
  echo "  '$platform': ('$url', '$sum')," >> "$tmp/pin.dart"
  echo "$platform $sum" >&2
done
echo "};" >> "$tmp/pin.dart"
mv "$tmp/pin.dart" "$out"
echo "wrote $out ($version)"
